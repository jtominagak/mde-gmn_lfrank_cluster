#!/usr/bin/env bash
# Diffs this job's <py_src> + <sbatch_src> (see usage below) against a
# single rolling "last submitted" snapshot cache for that pipeline
# ($PROJ_DIR/results/.snapshots/ -- one <sbatch_src>/<py_src> pair per
# pipeline, keyed by basename, shared across every job of that pipeline
# rather than one copy per job/job dir), inserts a new entry for this job
# into $PROJ_DIR/JOB_LOG.md summarizing what changed since that previous
# job (MODIFIABLE PARAMETERS block diffs as a table, code/design diffs as
# unified diffs for both files), then overwrites the cache with this
# job's files so the *next* submission diffs against this one.
#
# Deliberately not a per-job copy under $OUT_DIR: every job's own
# .py/.sbatch content is byte-identical to either the live canonical
# scripts/batch/ + scripts/src/ files (the common case) or, if edited
# again since, fully reconstructable from JOB_LOG.md's own diff history
# (every change between consecutive jobs of a pipeline is already
# recorded there in full) -- keeping a full duplicate copy per job dir on
# top of that is pure redundancy that grows without bound. JOB_LOG.md is
# the single source of truth for "what changed and when"; this script's
# only job is to keep feeding it accurate diffs.
#
# JOB_LOG.md is a single running record across all jobs and all pipelines
# (newest entry first), not a per-job file -- entries are *inserted*
# right after a fixed marker line rather than the file being freshly
# written each time.
#
# Idempotent by design: if JOB_LOG.md already has an entry for this
# JOB_ID (a "## Job <id>" heading), this is a no-op -- no diff is
# recomputed and the snapshot cache is left untouched. That's what lets
# scripts/batch/submit.sh generate the entry immediately at submission
# time (rather than waiting for the job to reach the front of the queue)
# -- and lets a plain-language summary added on top of that pre-generated
# entry survive the job's own startup call to this same script without
# being duplicated, overwritten, or double-counted against the cache.
#
# Deliberately not `set -e`: diff/grep exit non-zero whenever they find
# no match/difference, which is the normal case here, not an error.
set -uo pipefail

usage() {
    echo "Usage: $0 <proj_dir> <out_dir> <job_id> <sbatch_src> <py_src>" >&2
    exit 1
}
[ "$#" -eq 5 ] || usage

PROJ_DIR="$1"
OUT_DIR="$2"
JOB_ID="$3"
SBATCH_SRC="$4"
PY_SRC="$5"

RESULTS_DIR="$PROJ_DIR/results"
LOG_FILE="$PROJ_DIR/JOB_LOG.md"
ENTRY_MARKER="<!-- new entries inserted below this line -->"
# Keyed by basename (not hardcoded to any one pipeline's filenames) since
# this script is shared -- scripts/batch/tsls-mde-gmn.sbatch calls it too,
# with tsls-mde-gmn.sbatch/.py as SBATCH_SRC/PY_SRC. This is what keeps a
# tsls-mde-gmn job's diff from ever being computed against a
# simple-mde-gmn snapshot, or vice versa.
SBATCH_NAME="$(basename "$SBATCH_SRC")"
PY_NAME="$(basename "$PY_SRC")"
SNAP_DIR="$RESULTS_DIR/.snapshots"
CACHE_SBATCH="$SNAP_DIR/$SBATCH_NAME"
CACHE_PY="$SNAP_DIR/$PY_NAME"
CACHE_JOB_ID_FILE="$SNAP_DIR/$SBATCH_NAME.job_id"

if grep -qF "## Job ${JOB_ID}" "$LOG_FILE" 2>/dev/null; then
    echo "Job ${JOB_ID} already has an entry in $LOG_FILE -- leaving it (and the snapshot cache) as-is (likely pre-generated by submit.sh)."
    exit 0
fi

mkdir -p "$OUT_DIR" "$SNAP_DIR"

# Extract KEY=VALUE lines from the MODIFIABLE PARAMETERS block, comments
# and quotes stripped, so cosmetic differences (quoting, trailing comment
# wording) don't show up as a "change".
extract_params() {
    awk '/# MODIFIABLE PARAMETERS/{flag=1; next} /# ENVIRONMENT SETUP/{flag=0} flag' "$1" \
        | grep -E '^[A-Z_][A-Z0-9_]*=' \
        | tr -d '"' \
        | sed -E 's/[[:space:]]*#.*$//; s/[[:space:]]+$//'
}

# Everything outside the MODIFIABLE PARAMETERS block, so the design-change
# diff doesn't just re-show every parameter edit already covered above.
strip_params() {
    awk '/# MODIFIABLE PARAMETERS/{flag=1} /# ENVIRONMENT SETUP/{flag=0; print; next} !flag' "$1"
}

entry_file="$(mktemp)"
trap 'rm -f "$entry_file"' EXIT

{
    echo "## Job ${JOB_ID}"
    echo
    echo "Generated: $(date -Iseconds)"
    echo

    if git -C "$PROJ_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        commit="$(git -C "$PROJ_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
        dirty="clean vs. HEAD"
        git -C "$PROJ_DIR" diff --quiet -- "$PY_SRC" "$SBATCH_SRC" 2>/dev/null || dirty="uncommitted local changes vs. HEAD"
        echo "Git commit at submission: \`${commit}\` (${dirty})"
        echo
    fi

    if [ ! -f "$CACHE_SBATCH" ] || [ ! -f "$CACHE_PY" ]; then
        echo "No previous job snapshot found -- this is the first tracked run of this pipeline, or all prior jobs predate this tracking."
    else
        prev_id="$(cat "$CACHE_JOB_ID_FILE" 2>/dev/null || echo unknown)"
        echo "Compared against: **job_${prev_id}**"
        echo

        echo "### Parameter changes ($SBATCH_NAME)"
        echo
        old_params="$(extract_params "$CACHE_SBATCH")"
        new_params="$(extract_params "$SBATCH_SRC")"
        if [ "$old_params" = "$new_params" ]; then
            echo "_No parameter changes._"
        else
            echo "| Parameter | job_${prev_id} | job_${JOB_ID} |"
            echo "|---|---|---|"
            keys="$(printf '%s\n%s\n' "$old_params" "$new_params" | grep -oE '^[A-Z_][A-Z0-9_]*' | sort -u)"
            while IFS= read -r key; do
                [ -n "$key" ] || continue
                old_val="$(printf '%s\n' "$old_params" | grep -E "^${key}=" | sed -E "s/^${key}=//")"
                new_val="$(printf '%s\n' "$new_params" | grep -E "^${key}=" | sed -E "s/^${key}=//")"
                if [ "$old_val" != "$new_val" ]; then
                    echo "| ${key} | ${old_val:-_(unset)_} | ${new_val:-_(unset)_} |"
                fi
            done <<< "$keys"
        fi
        echo

        echo "### Batch script design changes ($SBATCH_NAME, excludes parameter block above)"
        echo
        if diff -q <(strip_params "$CACHE_SBATCH") <(strip_params "$SBATCH_SRC") >/dev/null; then
            echo "_No changes._"
        else
            echo '```diff'
            diff -u --label "job_${prev_id}/$SBATCH_NAME" --label "job_${JOB_ID}/$SBATCH_NAME" \
                <(strip_params "$CACHE_SBATCH") <(strip_params "$SBATCH_SRC")
            echo '```'
        fi
        echo

        echo "### Python pipeline changes ($PY_NAME)"
        echo
        if diff -q "$CACHE_PY" "$PY_SRC" >/dev/null; then
            echo "_No changes._"
        else
            echo '```diff'
            diff -u --label "job_${prev_id}/$PY_NAME" --label "job_${JOB_ID}/$PY_NAME" \
                "$CACHE_PY" "$PY_SRC"
            echo '```'
        fi
    fi
    echo
    echo "---"
    echo
} > "$entry_file"

if [ ! -f "$LOG_FILE" ]; then
    {
        echo "# Job Log"
        echo
        echo "Running record of parameter and pipeline/design changes across job"
        echo "submissions (see scripts/batch/submit.sh), newest entry first."
        echo
        echo "$ENTRY_MARKER"
        echo
    } > "$LOG_FILE"
fi

tmp_log="$(mktemp)"
awk -v entry="$entry_file" -v marker="$ENTRY_MARKER" '
{
    print
    if (index($0, marker) > 0) {
        print ""
        while ((getline line < entry) > 0) print line
    }
}
' "$LOG_FILE" > "$tmp_log" && mv "$tmp_log" "$LOG_FILE"

# Update the rolling cache to this job's files, so the *next* submission
# of this pipeline diffs against this one. Done last, only after the
# JOB_LOG.md entry above was written successfully.
cp -p "$SBATCH_SRC" "$CACHE_SBATCH"
cp -p "$PY_SRC" "$CACHE_PY"
echo "$JOB_ID" > "$CACHE_JOB_ID_FILE"

echo "Wrote job ${JOB_ID} entry to $LOG_FILE"
