#!/usr/bin/env bash
# =============================================================================
# generate_job_description.sh -- write this job's JOB_LOG.md entry
# =============================================================================
#     generate_job_description.sh <proj_dir> <job_id> <sbatch_src> <py_src>
#
# Records what changed since the previous job OF THE SAME PIPELINE: the
# MODIFIABLE PARAMETERS block as a table of changed values, and the sbatch's
# own design plus the whole Python source tree as unified diffs.
#
# HOW THE COMPARISON WORKS. One rolling snapshot per pipeline, under
# $SNAP_DIR/<sbatch basename>/, holding that pipeline's last-submitted sbatch
# and a copy of its src/ tree. This job diffs against that snapshot, then
# replaces it, so the next submission diffs against this one. Keyed by sbatch
# basename, which is what keeps one pipeline's diff from ever being computed
# against another's.
#
# WHAT IS DIFFED, AND WHY IT IS THE WHOLE TREE. The <py_src> argument names the
# ENTRY SCRIPT, which is about fifteen lines of boilerplate -- all the real code
# is in the mde_gmn package and edm.py beside it. Diffing only that file
# reported "_No changes._" for every single job while the pipeline underneath
# was being rewritten, which made the log useless for exactly the question it
# exists to answer. So the snapshot covers every .py file under src/, and
# <py_src> now only identifies WHICH entry script this job runs.
#
# IDEMPOTENT. If JOB_LOG.md already has a "## Job <id>" heading, this is a
# no-op: no diff is recomputed and the snapshot is left alone. That is what
# lets submit.sh write the entry at submission time, and lets a summary added
# to it by hand survive the job's own startup call to this same script.
#
# WHERE THE LOG LIVES. $PAO_JOB_LOG, defaulting to JOB_LOG.md one level above
# <proj_dir> -- a single running record across every pipeline, newest first,
# with entries INSERTED after a fixed marker rather than the file being
# rewritten.
#
# Deliberately not `set -e`: diff and grep exit non-zero when they find no
# difference or no match, which here is the normal case, not an error.
# =============================================================================
set -uo pipefail

usage() { echo "Usage: $0 <proj_dir> <job_id> <sbatch_src> <py_src>" >&2; exit 1; }
[ "$#" -eq 4 ] || usage

PROJ_DIR="$1"
JOB_ID="$2"
SBATCH_SRC="$3"
PY_SRC="$4"

SBATCH_NAME="$(basename "$SBATCH_SRC")"
PY_NAME="$(basename "$PY_SRC")"
SRC_DIR="$PROJ_DIR/src"

LOG_FILE="${PAO_JOB_LOG:-$(dirname "$PROJ_DIR")/JOB_LOG.md}"
SNAP_DIR="${PAO_SNAPSHOT_DIR:-$(dirname "$PROJ_DIR")/results/.snapshots}/$SBATCH_NAME"
CACHE_SBATCH="$SNAP_DIR/sbatch"
CACHE_SRC="$SNAP_DIR/src"
CACHE_JOB_ID_FILE="$SNAP_DIR/job_id"
ENTRY_MARKER="<!-- new entries inserted below this line -->"

if grep -qF "## Job ${JOB_ID}" "$LOG_FILE" 2>/dev/null; then
    echo "Job ${JOB_ID} already has an entry in $LOG_FILE -- leaving it and the" \
         "snapshot as-is (pre-generated by submit.sh)."
    exit 0
fi

mkdir -p "$SNAP_DIR"

# KEY=VALUE lines from the MODIFIABLE PARAMETERS block, comments and quotes
# stripped, so cosmetic differences (quoting, comment wording) are not reported
# as parameter changes.
extract_params() {
    awk '/# MODIFIABLE PARAMETERS/{flag=1; next} /# ENVIRONMENT SETUP/{flag=0} flag' "$1" \
        | grep -E '^[A-Z_][A-Z0-9_]*=' \
        | tr -d '"' \
        | sed -E 's/[[:space:]]*#.*$//; s/[[:space:]]+$//'
}

# Everything OUTSIDE that block, so the design diff does not just re-show every
# parameter edit the table already covers.
strip_params() {
    awk '/# MODIFIABLE PARAMETERS/{flag=1} /# ENVIRONMENT SETUP/{flag=0; print; next} !flag' "$1"
}

entry_file="$(mktemp)"
trap 'rm -f "$entry_file"' EXIT

{
    echo "## Job ${JOB_ID}"
    echo
    echo "Generated: $(date -Iseconds)"
    echo "Pipeline: \`${SBATCH_NAME}\` running \`${PY_NAME}\`"
    echo

    if git -C "$PROJ_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        commit="$(git -C "$PROJ_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
        dirty="clean vs. HEAD"
        git -C "$PROJ_DIR" diff --quiet -- "$SBATCH_SRC" "$SRC_DIR" 2>/dev/null \
            || dirty="uncommitted local changes vs. HEAD"
        echo "Git commit at submission: \`${commit}\` (${dirty})"
        echo
    fi

    if [ ! -f "$CACHE_SBATCH" ] || [ ! -d "$CACHE_SRC" ]; then
        echo "No previous snapshot for this pipeline -- this is its first tracked run."
    else
        prev_id="$(cat "$CACHE_JOB_ID_FILE" 2>/dev/null || echo unknown)"
        echo "Compared against: **job_${prev_id}**"
        echo

        echo "### Parameter changes (${SBATCH_NAME})"
        echo
        old_params="$(extract_params "$CACHE_SBATCH")"
        new_params="$(extract_params "$SBATCH_SRC")"
        if [ "$old_params" = "$new_params" ]; then
            echo "_No parameter changes._"
        else
            echo "| Parameter | job_${prev_id} | job_${JOB_ID} |"
            echo "|---|---|---|"
            printf '%s\n%s\n' "$old_params" "$new_params" \
                | grep -oE '^[A-Z_][A-Z0-9_]*' | sort -u \
                | while IFS= read -r key; do
                    [ -n "$key" ] || continue
                    old_val="$(printf '%s\n' "$old_params" | grep -E "^${key}=" | sed -E "s/^${key}=//")"
                    new_val="$(printf '%s\n' "$new_params" | grep -E "^${key}=" | sed -E "s/^${key}=//")"
                    [ "$old_val" = "$new_val" ] && continue
                    echo "| ${key} | ${old_val:-_(unset)_} | ${new_val:-_(unset)_} |"
                  done
        fi
        echo

        echo "### Batch script design changes (${SBATCH_NAME}, excludes the table above)"
        echo
        if diff -q <(strip_params "$CACHE_SBATCH") <(strip_params "$SBATCH_SRC") >/dev/null; then
            echo "_No changes._"
        else
            echo '```diff'
            diff -u --label "job_${prev_id}/${SBATCH_NAME}" --label "job_${JOB_ID}/${SBATCH_NAME}" \
                <(strip_params "$CACHE_SBATCH") <(strip_params "$SBATCH_SRC")
            echo '```'
        fi
        echo

        echo "### Python source changes (every .py under src/)"
        echo
        if diff -rq -x '__pycache__' "$CACHE_SRC" "$SRC_DIR" >/dev/null 2>&1; then
            echo "_No changes._"
        else
            echo '```diff'
            # Recursive, so a change anywhere in the package shows up. The two
            # long absolute roots are rewritten to job_<id>/src so the diff
            # reads the way the sbatch one above does.
            diff -ru -x '__pycache__' "$CACHE_SRC" "$SRC_DIR" \
                | sed -e "s|${CACHE_SRC}|job_${prev_id}/src|g" \
                      -e "s|${SRC_DIR}|job_${JOB_ID}/src|g"
            echo '```'
        fi
    fi
    echo
    echo "---"
    echo
} > "$entry_file"

if [ ! -f "$LOG_FILE" ]; then
    {
        echo "# Job Log"
        echo
        echo "Running record of parameter and code changes across job submissions"
        echo "(see batch/submit.sh), newest entry first."
        echo
        echo "$ENTRY_MARKER"
        echo
    } > "$LOG_FILE"
fi

tmp_log="$(mktemp)"
awk -v entry="$entry_file" -v marker="$ENTRY_MARKER" '
{
    print
    if (index($0, marker) > 0) {
        print ""
        while ((getline line < entry) > 0) print line
    }
}
' "$LOG_FILE" > "$tmp_log" && mv "$tmp_log" "$LOG_FILE"

# Roll the snapshot forward to this job's files, so the NEXT submission of this
# pipeline diffs against this one. Done last, and only once the JOB_LOG.md
# entry above has been written successfully.
cp -p "$SBATCH_SRC" "$CACHE_SBATCH"
rm -rf "$CACHE_SRC"
mkdir -p "$CACHE_SRC"
# Only the sources, never __pycache__ -- a stale .pyc in the snapshot would
# show up as a binary-files-differ line in every subsequent diff.
(cd "$SRC_DIR" && find . -name '__pycache__' -prune -o -name '*.py' -print0) \
    | (cd "$SRC_DIR" && xargs -0 -I{} cp -p --parents {} "$CACHE_SRC"/)
echo "$JOB_ID" > "$CACHE_JOB_ID_FILE"

echo "Wrote job ${JOB_ID} entry to $LOG_FILE"
